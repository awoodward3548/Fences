create extension if not exists pgcrypto with schema extensions;

-- ---------- Tables ----------

create table if not exists league (
  id int primary key default 1 check (id = 1),
  name text not null default 'Indoor Golf League',
  settings jsonb not null default '{}'::jsonb,
  current_week_id int,
  admin_pin_hash text
);

create table if not exists tees (
  id int generated by default as identity primary key,
  name text not null,
  color text not null default '#ffffff',
  yards int,
  active boolean not null default true,
  sort int not null default 0
);

create table if not exists teams (
  id int generated by default as identity primary key,
  name text not null,
  player1 text not null default '',
  player2 text not null default '',
  tee1 int,
  tee2 int,
  active boolean not null default true,
  sort int not null default 0,
  pin_hash text
);

create table if not exists weeks (
  id int generated by default as identity primary key,
  num int not null default 0,
  label text not null default '',
  play_date date,
  is_final boolean not null default false,
  course text not null default '',
  pars int[],
  sis int[],
  tee_pars jsonb not null default '{}'::jsonb,
  setup_done boolean not null default false
);

-- Each week keeps the handicap and tees that applied that week.
create table if not exists week_teams (
  week_id int not null references weeks(id) on delete cascade,
  team_id int not null references teams(id) on delete cascade,
  handicap int not null default 0,
  tee1 int,
  tee2 int,
  primary key (week_id, team_id)
);

-- One card per team per week. Once a row exists the card is locked for the team.
create table if not exists cards (
  week_id int not null references weeks(id) on delete cascade,
  team_id int not null references teams(id) on delete cascade,
  gross int[],
  status text not null check (status in ('submitted', 'absent')),
  entered_by text not null default 'team',
  submitted_at timestamptz not null default now(),
  primary key (week_id, team_id)
);

create table if not exists change_log (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  who text not null default '',
  action text not null,
  week_id int,
  team_id int,
  old_value jsonb,
  new_value jsonb,
  reason text not null default ''
);

create table if not exists pin_attempts (
  key text not null,
  at timestamptz not null default now()
);
create index if not exists pin_attempts_key_at on pin_attempts (key, at);

-- Lock every table: the public key can only call the functions below.
do $$
declare t text;
begin
  foreach t in array array['league','tees','teams','weeks','week_teams','cards','change_log','pin_attempts'] loop
    execute format('alter table %I enable row level security', t);
    execute format('revoke all on table %I from anon, authenticated', t);
  end loop;
end $$;

