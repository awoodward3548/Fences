do $$
declare f record;
begin
  for f in select p.oid::regprocedure as sig, p.proname from pg_proc p join pg_namespace n on n.oid = p.pronamespace
           where n.nspname = 'public' and p.proname in (
             '_err','_pin_check','_admin','_hash','_valid_scores','_log',
             'get_league','check_team_pin','submit_card','admin_claim','admin_check','admin_change_pin',
             'admin_save_settings','admin_save_tee','admin_save_team','admin_set_team_pin','admin_save_week',
             'admin_delete_week','admin_save_week_setup','admin_save_card') loop
    execute format('revoke all on function %s from public, anon, authenticated', f.sig);
    if left(f.proname, 1) <> '_' then
      execute format('grant execute on function %s to anon, authenticated', f.sig);
    end if;
  end loop;
end $$;

