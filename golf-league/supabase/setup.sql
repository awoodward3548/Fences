-- ---------- Helpers (not callable from the website) ----------

create or replace function _err(msg text) returns jsonb
language sql immutable as $$ select jsonb_build_object('ok', false, 'error', msg) $$;

-- Returns an error message, or null when the PIN is right. Slows down guessing.
create or replace function _pin_check(p_key text, p_hash text, p_pin text) returns text
language plpgsql security definer set search_path = public, extensions as $$
begin
  delete from pin_attempts where at < now() - interval '1 day';
  if (select count(*) from pin_attempts where key = p_key and at > now() - interval '10 minutes') >= 8 then
    return 'Too many wrong PINs. Please wait 10 minutes and try again.';
  end if;
  if p_hash is null then
    return 'No PIN has been set yet. Ask the league admin.';
  end if;
  if p_pin is null or extensions.crypt(p_pin, p_hash) <> p_hash then
    insert into pin_attempts (key) values (p_key);
    return 'Wrong PIN. Try again.';
  end if;
  delete from pin_attempts where key = p_key;
  return null;
end $$;

create or replace function _admin(p_pin text) returns text
language plpgsql security definer set search_path = public, extensions as $$
begin
  return _pin_check('admin', (select admin_pin_hash from league where id = 1), p_pin);
end $$;

create or replace function _hash(p_pin text) returns text
language sql security definer set search_path = public, extensions as $$
  select extensions.crypt(p_pin, extensions.gen_salt('bf', 8))
$$;

create or replace function _valid_scores(g int[]) returns boolean
language sql immutable as $$
  select g is not null and array_length(g, 1) = 12 and array_ndims(g) = 1
     and not exists (select 1 from unnest(g) x where x is null or x < 1 or x > 30)
$$;

create or replace function _log(p_who text, p_action text, p_week int, p_team int, p_old jsonb, p_new jsonb, p_reason text)
returns void language sql security definer set search_path = public as $$
  insert into change_log (who, action, week_id, team_id, old_value, new_value, reason)
  values (coalesce(nullif(trim(p_who), ''), 'Admin'), p_action, p_week, p_team, p_old, p_new, coalesce(p_reason, ''));
$$;

-- ---------- Public: read everything (no PINs) ----------

create or replace function get_league() returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object('ok', true, 'data', jsonb_build_object(
    'league', (select jsonb_build_object('name', name, 'settings', settings, 'current_week_id', current_week_id,
                                         'admin_set', admin_pin_hash is not null) from league where id = 1),
    'tees', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'name', name, 'color', color, 'yards', yards,
                                       'active', active, 'sort', sort) order by sort, id) from tees), '[]'::jsonb),
    'teams', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'name', name, 'player1', player1, 'player2', player2,
                                        'tee1', tee1, 'tee2', tee2, 'active', active, 'sort', sort,
                                        'has_pin', pin_hash is not null) order by sort, id) from teams), '[]'::jsonb),
    'weeks', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'num', num, 'label', label, 'play_date', play_date,
                                        'is_final', is_final, 'course', course, 'pars', pars, 'sis', sis,
                                        'tee_pars', tee_pars, 'setup_done', setup_done) order by play_date, num, id) from weeks), '[]'::jsonb),
    'week_teams', coalesce((select jsonb_agg(to_jsonb(wt)) from week_teams wt), '[]'::jsonb),
    'cards', coalesce((select jsonb_agg(jsonb_build_object('week_id', week_id, 'team_id', team_id, 'gross', gross,
                                        'status', status, 'entered_by', entered_by, 'submitted_at', submitted_at)) from cards), '[]'::jsonb),
    'log', coalesce((select jsonb_agg(to_jsonb(l) order by l.at desc, l.id desc) from change_log l), '[]'::jsonb)
  ))
$$;

-- ---------- Teams ----------

create or replace function check_team_pin(p_team_id int, p_pin text) returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare e text;
begin
  e := _pin_check('team:' || p_team_id, (select pin_hash from teams where id = p_team_id and active), p_pin);
  if e is not null then return _err(e); end if;
  return jsonb_build_object('ok', true);
end $$;

create or replace function submit_card(p_week_id int, p_team_id int, p_pin text, p_gross int[]) returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare w weeks; e text; tname text;
begin
  select * into w from weeks where id = p_week_id;
  if not found or not w.setup_done then return _err('This week is not open for scores yet.'); end if;
  select name into tname from teams where id = p_team_id and active;
  if tname is null then return _err('Team not found.'); end if;
  e := _pin_check('team:' || p_team_id, (select pin_hash from teams where id = p_team_id), p_pin);
  if e is not null then return _err(e); end if;
  if exists (select 1 from cards where week_id = p_week_id and team_id = p_team_id) then
    return jsonb_build_object('ok', false, 'locked', true, 'error', 'This card is already submitted and locked.');
  end if;
  if not exists (select 1 from week_teams where week_id = p_week_id and team_id = p_team_id) then
    return _err('Your team is not set up for this week yet. Ask the league admin.');
  end if;
  if not _valid_scores(p_gross) then return _err('Every hole needs a score between 1 and 30.'); end if;
  insert into cards (week_id, team_id, gross, status, entered_by)
  values (p_week_id, p_team_id, p_gross, 'submitted', 'team')
  on conflict do nothing;
  if not found then
    return jsonb_build_object('ok', false, 'locked', true, 'error', 'This card is already submitted and locked.');
  end if;
  perform _log(tname, 'Card submitted', p_week_id, p_team_id, null, to_jsonb(p_gross), '');
  return jsonb_build_object('ok', true);
end $$;

