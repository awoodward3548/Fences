-- First-time setup only: works while no admin PIN exists.
create or replace function admin_claim(p_new_pin text) returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
begin
  if p_new_pin !~ '^\d{4,8}$' then return _err('The admin PIN must be 4 to 8 digits.'); end if;
  update league set admin_pin_hash = _hash(p_new_pin) where id = 1 and admin_pin_hash is null;
  if not found then return _err('An admin PIN is already set.'); end if;
  return jsonb_build_object('ok', true);
end $$;

create or replace function admin_check(p_pin text) returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare e text := _admin(p_pin);
begin
  if e is not null then return _err(e); end if;
  return jsonb_build_object('ok', true);
end $$;

create or replace function admin_change_pin(p_pin text, p_who text, p_new_pin text) returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare e text := _admin(p_pin);
begin
  if e is not null then return _err(e); end if;
  if p_new_pin !~ '^\d{4,8}$' then return _err('The admin PIN must be 4 to 8 digits.'); end if;
  update league set admin_pin_hash = _hash(p_new_pin) where id = 1;
  perform _log(p_who, 'Admin PIN changed', null, null, null, null, '');
  return jsonb_build_object('ok', true);
end $$;

create or replace function admin_save_settings(p_pin text, p_who text, p_name text, p_settings jsonb, p_current_week_id int) returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare e text := _admin(p_pin); old jsonb;
begin
  if e is not null then return _err(e); end if;
  if jsonb_typeof(p_settings) <> 'object' then return _err('Bad settings.'); end if;
  select jsonb_build_object('name', name, 'settings', settings, 'current_week_id', current_week_id) into old from league where id = 1;
  update league set name = coalesce(nullif(trim(p_name), ''), name), settings = p_settings, current_week_id = p_current_week_id where id = 1;
  perform _log(p_who, 'Rules changed', null, null, old,
               jsonb_build_object('name', p_name, 'settings', p_settings, 'current_week_id', p_current_week_id), '');
  return jsonb_build_object('ok', true);
end $$;

create or replace function admin_save_tee(p_pin text, p_who text, p_tee jsonb) returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare e text := _admin(p_pin); tid int := (p_tee->>'id')::int;
begin
  if e is not null then return _err(e); end if;
  if coalesce(trim(p_tee->>'name'), '') = '' then return _err('The tee needs a name.'); end if;
  if tid is null then
    insert into tees (name, color, yards, sort)
    values (trim(p_tee->>'name'), coalesce(p_tee->>'color', '#ffffff'), nullif(p_tee->>'yards', '')::int,
            coalesce((select max(sort) + 1 from tees), 1));
  else
    update tees set name = trim(p_tee->>'name'), color = coalesce(p_tee->>'color', color),
      yards = nullif(p_tee->>'yards', '')::int, active = coalesce((p_tee->>'active')::boolean, active)
    where id = tid;
  end if;
  return jsonb_build_object('ok', true);
end $$;

create or replace function admin_save_team(p_pin text, p_who text, p_team jsonb) returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare e text := _admin(p_pin); tid int := (p_team->>'id')::int; old jsonb;
begin
  if e is not null then return _err(e); end if;
  if coalesce(trim(p_team->>'name'), '') = '' then return _err('The team needs a name.'); end if;
  if tid is null then
    insert into teams (name, player1, player2, tee1, tee2, sort)
    values (trim(p_team->>'name'), coalesce(trim(p_team->>'player1'), ''), coalesce(trim(p_team->>'player2'), ''),
            (p_team->>'tee1')::int, (p_team->>'tee2')::int, coalesce((select max(sort) + 1 from teams), 1))
    returning id into tid;
    perform _log(p_who, 'Team added', null, tid, null, p_team - 'pin', '');
  else
    select to_jsonb(t) - 'pin_hash' into old from teams t where id = tid;
    update teams set name = trim(p_team->>'name'), player1 = coalesce(trim(p_team->>'player1'), ''),
      player2 = coalesce(trim(p_team->>'player2'), ''), tee1 = (p_team->>'tee1')::int, tee2 = (p_team->>'tee2')::int,
      active = coalesce((p_team->>'active')::boolean, active)
    where id = tid;
    if old->>'name' is distinct from trim(p_team->>'name') or old->>'active' is distinct from coalesce(p_team->>'active', old->>'active') then
      perform _log(p_who, 'Team changed', null, tid, old, p_team, '');
    end if;
  end if;
  return jsonb_build_object('ok', true, 'id', tid);
end $$;

create or replace function admin_set_team_pin(p_pin text, p_who text, p_team_id int, p_new_pin text) returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare e text := _admin(p_pin);
begin
  if e is not null then return _err(e); end if;
  if p_new_pin !~ '^\d{4}$' then return _err('Team PINs are exactly 4 digits.'); end if;
  update teams set pin_hash = _hash(p_new_pin) where id = p_team_id;
  if not found then return _err('Team not found.'); end if;
  delete from pin_attempts where key = 'team:' || p_team_id;
  perform _log(p_who, 'Team PIN reset', null, p_team_id, null, null, '');
  return jsonb_build_object('ok', true);
end $$;

create or replace function admin_save_week(p_pin text, p_who text, p_week jsonb) returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare e text := _admin(p_pin); wid int := (p_week->>'id')::int; old jsonb;
begin
  if e is not null then return _err(e); end if;
  if nullif(p_week->>'play_date', '') is null then return _err('Pick a date.'); end if;
  if coalesce((p_week->>'is_final')::boolean, false)
     and exists (select 1 from weeks where is_final and id is distinct from wid) then
    return _err('There is already a final. Untick the other one first.');
  end if;
  if wid is null then
    insert into weeks (num, label, play_date, is_final)
    values (coalesce((p_week->>'num')::int, 0), coalesce(p_week->>'label', ''), (p_week->>'play_date')::date,
            coalesce((p_week->>'is_final')::boolean, false))
    returning id into wid;
    perform _log(p_who, 'Week added', wid, null, null, p_week, '');
  else
    select jsonb_build_object('num', num, 'label', label, 'play_date', play_date, 'is_final', is_final) into old from weeks where id = wid;
    update weeks set num = coalesce((p_week->>'num')::int, num), label = coalesce(p_week->>'label', label),
      play_date = (p_week->>'play_date')::date, is_final = coalesce((p_week->>'is_final')::boolean, is_final)
    where id = wid;
    perform _log(p_who, 'Schedule changed', wid, null, old, p_week, '');
  end if;
  return jsonb_build_object('ok', true, 'id', wid);
end $$;

create or replace function admin_delete_week(p_pin text, p_who text, p_week_id int) returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare e text := _admin(p_pin); old jsonb;
begin
  if e is not null then return _err(e); end if;
  if exists (select 1 from cards where week_id = p_week_id) then
    return _err('This week already has scores, so it can''t be deleted.');
  end if;
  select jsonb_build_object('label', label, 'play_date', play_date) into old from weeks where id = p_week_id;
  delete from weeks where id = p_week_id;
  update league set current_week_id = null where current_week_id = p_week_id;
  perform _log(p_who, 'Week deleted', null, null, old, null, '');
  return jsonb_build_object('ok', true);
end $$;

-- Weekly setup: course, par, stroke index, every team's handicap and tees.
-- p_teams: [{"team_id":1,"handicap":4,"tee1":3,"tee2":3}, ...]
create or replace function admin_save_week_setup(p_pin text, p_who text, p_week_id int, p_course text,
  p_pars int[], p_sis int[], p_tee_pars jsonb, p_teams jsonb, p_open boolean, p_reason text) returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare e text := _admin(p_pin); has_cards boolean; old jsonb; neu jsonb;
begin
  if e is not null then return _err(e); end if;
  if not exists (select 1 from weeks where id = p_week_id) then return _err('Week not found.'); end if;
  if coalesce(trim(p_course), '') = '' then return _err('Enter the course name.'); end if;
  if p_pars is null or array_length(p_pars, 1) <> 12 or exists (select 1 from unnest(p_pars) x where x is null or x < 2 or x > 7) then
    return _err('Every hole needs a par between 2 and 7.');
  end if;
  if p_sis is null or array_length(p_sis, 1) <> 12 or exists (select 1 from unnest(p_sis) x where x is null or x < 1 or x > 18) then
    return _err('Every hole needs a stroke index (hole handicap) between 1 and 18.');
  end if;
  if jsonb_typeof(coalesce(p_teams, '[]'::jsonb)) <> 'array' then return _err('Bad team list.'); end if;
  has_cards := exists (select 1 from cards where week_id = p_week_id);
  if has_cards and coalesce(trim(p_reason), '') = '' then
    return _err('Scores are already in for this week. Please give a reason for the change.');
  end if;
  if has_cards and not p_open then return _err('Scores are already in, so this week has to stay open.'); end if;

  select jsonb_build_object('course', w.course, 'pars', w.pars, 'sis', w.sis, 'tee_pars', w.tee_pars, 'open', w.setup_done,
    'teams', coalesce((select jsonb_agg(jsonb_build_object('team_id', team_id, 'handicap', handicap, 'tee1', tee1, 'tee2', tee2) order by team_id)
                       from week_teams where week_id = p_week_id), '[]'::jsonb))
  into old from weeks w where w.id = p_week_id;

  update weeks set course = trim(p_course), pars = p_pars, sis = p_sis,
    tee_pars = coalesce(p_tee_pars, '{}'::jsonb), setup_done = p_open
  where id = p_week_id;

  delete from week_teams where week_id = p_week_id;
  insert into week_teams (week_id, team_id, handicap, tee1, tee2)
  select p_week_id, x.team_id, coalesce(x.handicap, 0), x.tee1, coalesce(x.tee2, x.tee1)
  from jsonb_to_recordset(coalesce(p_teams, '[]'::jsonb)) as x(team_id int, handicap int, tee1 int, tee2 int)
  where exists (select 1 from teams t where t.id = x.team_id);

  neu := jsonb_build_object('course', trim(p_course), 'pars', p_pars, 'sis', p_sis, 'tee_pars', coalesce(p_tee_pars, '{}'::jsonb), 'open', p_open,
    'teams', coalesce((select jsonb_agg(jsonb_build_object('team_id', team_id, 'handicap', handicap, 'tee1', tee1, 'tee2', tee2) order by team_id)
                       from week_teams where week_id = p_week_id), '[]'::jsonb));
  if old is distinct from neu then
    perform _log(p_who, case when has_cards then 'Course/handicaps corrected' else 'Week set up' end,
                 p_week_id, null, old, neu, coalesce(p_reason, ''));
  end if;
  return jsonb_build_object('ok', true);
end $$;

-- Admin card fixes. p_action: 'set' (enter or correct scores), 'absent', 'unlock' (remove so the team can re-enter).
create or replace function admin_save_card(p_pin text, p_who text, p_week_id int, p_team_id int, p_action text,
  p_gross int[], p_reason text) returns jsonb
language plpgsql security definer set search_path = public, extensions as $$
declare e text := _admin(p_pin); c cards; existed boolean; old jsonb; act text;
begin
  if e is not null then return _err(e); end if;
  if not exists (select 1 from weeks where id = p_week_id) then return _err('Week not found.'); end if;
  if not exists (select 1 from teams where id = p_team_id) then return _err('Team not found.'); end if;
  select * into c from cards where week_id = p_week_id and team_id = p_team_id;
  existed := found;
  if existed and coalesce(trim(p_reason), '') = '' then
    return _err('This card is already in. Please give a reason for the change.');
  end if;
  old := case when existed then jsonb_build_object('status', c.status, 'gross', c.gross) else null end;

  if p_action = 'set' then
    if not _valid_scores(p_gross) then return _err('Every hole needs a score between 1 and 30.'); end if;
    if not exists (select 1 from week_teams where week_id = p_week_id and team_id = p_team_id) then
      return _err('Set up this team for the week first (Weekly setup).');
    end if;
    insert into cards (week_id, team_id, gross, status, entered_by) values (p_week_id, p_team_id, p_gross, 'submitted', 'admin')
    on conflict (week_id, team_id) do update set gross = excluded.gross, status = 'submitted', entered_by = 'admin';
    act := case when existed then 'Card corrected' else 'Card entered by admin' end;
    perform _log(p_who, act, p_week_id, p_team_id, old, jsonb_build_object('status', 'submitted', 'gross', p_gross), p_reason);
  elsif p_action = 'absent' then
    insert into cards (week_id, team_id, gross, status, entered_by) values (p_week_id, p_team_id, null, 'absent', 'admin')
    on conflict (week_id, team_id) do update set gross = null, status = 'absent', entered_by = 'admin';
    perform _log(p_who, 'Marked absent', p_week_id, p_team_id, old, jsonb_build_object('status', 'absent'), p_reason);
  elsif p_action = 'unlock' then
    if not existed then return _err('There is no card to unlock.'); end if;
    delete from cards where week_id = p_week_id and team_id = p_team_id;
    perform _log(p_who, 'Card unlocked', p_week_id, p_team_id, old, null, p_reason);
  else
    return _err('Unknown action.');
  end if;
  return jsonb_build_object('ok', true);
end $$;

